export function detectGender(fullName: string): "female" | "male" {
  const parts = fullName.toLowerCase().replace(/^dr\.?\s*/i, "").split(/\s+/);
  for (const part of parts) {
    if (FEMALE_NAMES.has(part)) return "female";
  }
  const last = parts[parts.length - 1] || "";
  if (["a", "i", "ya", "ee", "ni", "ti", "ta", "ra", "sha", "la", "ma", "na", "pa", "ka"].some(s => last.endsWith(s))) {
    return "female";
  }
  return "male";
}

export function getPhotoForDoctor(fullName: string, index: number): string {
  const gender = detectGender(fullName);
  const pool = gender === "female" ? FEMALE_PHOTOS : MALE_PHOTOS;
  // 22-23 unique real photos per gender — plenty for this app's doctor count,
  // so in practice every doctor gets their own distinct photo. If the pool
  // ever runs out we deliberately still pick from the *correct-gender* pool
  // (never crossing genders, never a cartoon) rather than showing nothing.
  return pool[index % pool.length];
}